def wc(body):
    return len(body.split())


def main():
    assert len(ARTICLES) == 8, "must be 8 articles"
    news = [a for a in ARTICLES if a["source_type"] == "news"]
    trend = [a for a in ARTICLES if a["source_type"] == "trend"]
    assert len(news) == 5 and len(trend) == 3, (len(news), len(trend))

    print("Word counts & checks:")
    for a in ARTICLES:
        assert "—" not in a["title"] + a["excerpt"] + a["body"], f"EM DASH in {a['slug']}"
        assert a["category"] in {"ЧМ-2026","Сборные","Отчёты о матчах","Новости игроков","Тренды"}, a["category"]
        assert a["type"] in {"transfer","preview","match_report","ranking"}, a["type"]
        assert a["sources"], a["slug"]
        print(f"  {a['type']:12} {wc(a['body']):4}w  {a['slug']}")

    # Build payload with optimized base64 cover images
    payload_articles = []
    print("\nOptimizing cover images…")
    for a in ARTICLES:
        b64, kb = make_16x9_b64(fp(IMG_FILE[a["img"]]))
        if not b64:
            raise SystemExit(f"IMAGE FAILED for {a['slug']} ({a['img']}) — cover is mandatory")
        print(f"  {a['img']:11} {kb:4}KB  -> {a['slug']}")
        payload_articles.append({
            "title": a["title"], "slug": a["slug"], "body": a["body"],
            "excerpt": a["excerpt"], "category": a["category"], "type": a["type"],
            "image_url": None, "image_base64": b64,
            "sources": a["sources"], "source_type": a["source_type"],
        })

    with open("scratchpad_payload.json", "w", encoding="utf-8") as f:
        json.dump({"generated_at": GEN_AT, "run_id": RUN_ID, "articles": payload_articles},
                  f, ensure_ascii=False)
    print("\nPayload saved to scratchpad_payload.json")

    if DRY_RUN:
        print("DRY RUN — not posting.")
        return

    def post_batch(items):
        body = json.dumps({"articles": items}, ensure_ascii=False).encode("utf-8")
        req = urllib.request.Request(ENDPOINT, data=body, method="POST")
        req.add_header("Content-Type", "application/json")
        req.add_header("x-agent-secret", SECRET)
        last = None
        for attempt in range(1, 5):  # retry transient resource/5xx errors
            try:
                with urllib.request.urlopen(req, timeout=180) as r:
                    return json.loads(r.read().decode()).get("results", [])
            except urllib.error.HTTPError as e:
                last = f"HTTP {e.code}: {e.read().decode()[:300]}"
            except Exception as e:
                last = str(e)
            print(f"    retry {attempt} after: {last}")
            __import__("time").sleep(2 ** attempt)
        print(f"    BATCH FAILED: {last}")
        return [{"slug": it["slug"], "status": "error", "error": last} for it in items]

    BATCH = 2
    print(f"\nPOSTing {len(payload_articles)} articles in batches of {BATCH}…")
    results = []
    for i in range(0, len(payload_articles), BATCH):
        chunk = payload_articles[i:i + BATCH]
        kb = len(json.dumps({"articles": chunk}, ensure_ascii=False).encode()) // 1024
        print(f"  batch {i//BATCH + 1}: {[c['slug'] for c in chunk]} ({kb} KB)")
        results.extend(post_batch(chunk))

    inserted, errors = [], []
    for it in results:
        st = it.get("status"); slug = it.get("slug")
        mark = "OK " if st == "inserted" else "ERR"
        print(f"  {mark} {slug} [{st}] {it.get('error','')}")
        (inserted if st == "inserted" else errors).append(it)
    resp = {"results": results}

    with open("scratchpad_results.json", "w", encoding="utf-8") as f:
        json.dump(resp, f, ensure_ascii=False, indent=2)
    print(f"\n{len(inserted)} inserted, {len(errors)} errors.")

    # ── Logging: append one line per inserted article + write last-run.json ──
    ts = datetime.now(timezone.utc).isoformat()
    log_path = "logs/articles-history.jsonl"
    os.makedirs("logs", exist_ok=True)
    by_slug = {a["slug"]: a for a in ARTICLES}
    db_slugs = []
    with open(log_path, "a", encoding="utf-8") as lf:
        for it in inserted:
            req_slug = it.get("_req_slug") or it.get("slug")
            src = by_slug.get(req_slug) or by_slug.get(it.get("slug"), {})
            db_slugs.append(it.get("slug"))
            entry = {
                "timestamp": ts, "run_id": RUN_ID, "source_type": src.get("source_type"),
                "type": src.get("type"), "title": src.get("title"),
                "slug": req_slug, "db_slug": it.get("slug"), "db_id": it.get("id"),
                "topic": (src.get("excerpt") or "")[:160],
                "teams": [], "players": [], "sources": src.get("sources", []),
            }
            lf.write(json.dumps(entry, ensure_ascii=False) + "\n")
    with open("logs/last-run.json", "w", encoding="utf-8") as f:
        json.dump({"run_id": RUN_ID, "generated_at": GEN_AT,
                   "counts": {"total": len(ARTICLES), "inserted": len(inserted), "errors": len(errors),
                              "news": 5, "trend": 3},
                   "db_slugs": db_slugs}, f, ensure_ascii=False, indent=2)
    print(f"Logged {len(db_slugs)} articles to {log_path}; last-run.json updated.")

    # Warn on -2/-3 suffix (would indicate an unexpected duplicate)
    for it in inserted:
        if re.search(r"-\d+$", it.get("slug", "")) and not by_slug.get(it.get("slug")):
            print(f"  ⚠ slug suffixed -> possible duplicate: {it.get('slug')}")


if __name__ == "__main__":
    main()
