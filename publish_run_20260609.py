# ---------------------------------------------------------------- image helper
def fetch_cover(url, tries=3):
    """Download an image, fit it onto a 1600x900 (16:9) canvas with a blurred
    background so the subject is never cropped, re-encode JPEG ~82%, return base64."""
    last = None
    for i in range(tries):
        try:
            r = S.get(url, timeout=60)
            if r.status_code == 200 and "image" in r.headers.get("content-type", ""):
                src = Image.open(io.BytesIO(r.content)).convert("RGB")
                TW, TH = 1600, 900
                # blurred cover background
                bg = src.copy()
                scale = max(TW / bg.width, TH / bg.height)
                bg = bg.resize((int(bg.width * scale), int(bg.height * scale)))
                left = (bg.width - TW) // 2; top = (bg.height - TH) // 2
                bg = bg.crop((left, top, left + TW, top + TH)).filter(ImageFilter.GaussianBlur(28))
                # contained foreground (whole subject visible)
                fg = src.copy()
                fscale = min(TW / fg.width, TH / fg.height)
                fg = fg.resize((max(1, int(fg.width * fscale)), max(1, int(fg.height * fscale))))
                bg.paste(fg, ((TW - fg.width) // 2, (TH - fg.height) // 2))
                out = io.BytesIO()
                bg.save(out, format="JPEG", quality=82, optimize=True)
                data = out.getvalue()
                print(f"   cover ok {len(data)//1024}KB  <- {url[:70]}")
                return base64.b64encode(data).decode("ascii")
            last = f"HTTP {r.status_code}"
        except Exception as e:
            last = str(e)
        time.sleep(4)  # Wikimedia rate-limit courtesy
    print(f"   cover FAILED ({last}) <- {url}")
    return None

