def main():
    if not SECRET:
        print("FATAL: AGENT_PUBLISH_SECRET not set"); return
    print(f"RUN {RUN_ID}  building {len(ARTICLES)} articles")
    payload = []
    for a in ARTICLES:
        print(f" - {a['slug']}")
        b64 = fetch_cover(a["img"])
        obj = {
            "title": a["title"], "slug": a["slug"], "body": a["body"],
            "excerpt": a["excerpt"], "category": a["category"], "type": a["type"],
            "image_url": None, "image_base64": b64,
            "sources": a["sources"], "source_type": a["source_type"],
        }
        a["_b64_ok"] = bool(b64)
        payload.append(obj)
        time.sleep(4)

    def post(items):
        r = S.post(ENDPOINT, headers={"Content-Type": "application/json",
                   "x-agent-secret": SECRET}, data=json.dumps({"articles": items}), timeout=120)
        print("HTTP", r.status_code)
        try:
            return r.status_code, r.json()
        except Exception:
            print(r.text[:500]); return r.status_code, None

    status, resp = post(payload)
    if status == 401:
        print("FATAL: 401 unauthorized — secret rejected. Stopping."); return
    results = (resp or {}).get("results", [])
    by_slug = {x.get("slug", "").rstrip("-23456789"): x for x in results}

    # retry errors once
    errs = [a for a, x in zip(payload, results) if x.get("status") == "error"] if len(results) == len(payload) else []
    if errs:
        print(f"retrying {len(errs)} errored items")
        time.sleep(3)
        _, resp2 = post(errs)
        for x in (resp2 or {}).get("results", []):
            results.append(x)

    # logging
    logdir = ROOT / "logs"; logdir.mkdir(exist_ok=True)
    hist = logdir / "articles-history.jsonl"
    inserted_slugs = []
    with hist.open("a", encoding="utf-8") as fh:
        for a, x in zip(ARTICLES, results):
            db_slug = x.get("slug"); st = x.get("status")
            if st == "inserted":
                inserted_slugs.append(db_slug)
            entry = {
                "timestamp": NOW, "run_id": RUN_ID, "publish_status": st,
                "db_id": x.get("id"), "db_slug": db_slug,
                "source_type": a["source_type"], "type": a["type"],
                "title": a["title"], "slug": a["slug"],
                "topic": a["excerpt"][:140],
                "image_url": x.get("image_url"), "has_base64_img": a.get("_b64_ok", False),
                "teams": [], "players": [],
                "sources": a["sources"],
            }
            fh.write(json.dumps(entry, ensure_ascii=False) + "\n")

    (logdir / "last-run.json").write_text(json.dumps({
        "run_id": RUN_ID, "generated_at": NOW, "count": len(ARTICLES),
        "news": sum(1 for a in ARTICLES if a["source_type"] == "news"),
        "trend": sum(1 for a in ARTICLES if a["source_type"] == "trend"),
        "inserted": len(inserted_slugs), "db_slugs": [x.get("slug") for x in results],
    }, ensure_ascii=False, indent=2), encoding="utf-8")

    # local archive
    for a in ARTICLES:
        src = "news-" if a["source_type"] == "news" else "trend-"
        d = ROOT / "articles" / f"{src}{a['slug']}"; d.mkdir(parents=True, exist_ok=True)
        (d / f"{src}{a['slug']}.md").write_text(
            f"# {a['title']}\n\n_{a['excerpt']}_\n\n{a['body']}\n", encoding="utf-8")

    print("\nRESULTS:")
    for x in results:
        print(f"  {x.get('status'):9} {x.get('slug')}  {x.get('error') or ''}")
    print(f"\ninserted {len(inserted_slugs)}/{len(ARTICLES)}")

if __name__ == "__main__":
    main()
