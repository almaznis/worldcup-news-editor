def build_payload(include_b64=True):
    out = []
    for a in ARTICLES:
        obj = {
            "title": a["title"], "slug": a["slug"], "body": a["body"],
            "excerpt": a["excerpt"], "category": a["category"], "type": a["type"],
            "image_url": None, "sources": a["sources"], "source_type": a["source_type"],
        }
        if include_b64:
            obj["image_base64"] = b64(a["cover"])
        else:
            obj["image_base64"] = None
        out.append(obj)
    return out

