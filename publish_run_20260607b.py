def letterbox_16x9(img_bytes, W=1280, H=720):
    """Centre the subject on a 16:9 canvas with a blurred fill background so a
    centre-crop keeps the whole face. Returns JPEG bytes."""
    src = Image.open(io.BytesIO(img_bytes)).convert("RGB")
    sw, sh = src.size
    # blurred cover background
    scale = max(W / sw, H / sh)
    bg = src.resize((int(sw * scale) + 1, int(sh * scale) + 1), Image.LANCZOS)
    bx = (bg.width - W) // 2
    by = (bg.height - H) // 2
    bg = bg.crop((bx, by, bx + W, by + H)).filter(ImageFilter.GaussianBlur(28))
    bg = Image.eval(bg, lambda p: int(p * 0.55))  # darken
    # foreground: contained with headroom (max 86% height, 92% width)
    fscale = min((W * 0.92) / sw, (H * 0.86) / sh)
    fw, fh = max(1, int(sw * fscale)), max(1, int(sh * fscale))
    fg = src.resize((fw, fh), Image.LANCZOS)
    canvas = bg.copy()
    canvas.paste(fg, ((W - fw) // 2, (H - fh) // 2))
    out = io.BytesIO()
    canvas.save(out, "JPEG", quality=86, optimize=True)
    return out.getvalue()

