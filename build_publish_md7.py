def cover_b64(url):
    """Letterbox any image onto a 1600x900 (16:9) canvas: blurred cover-fill background
    + fully-contained, centered foreground so the subject's face is never cropped."""
    raw = fetch(url)
    img = Image.open(io.BytesIO(raw)).convert("RGB")
    W, H = 1600, 900
    # background: fill + blur
    sc = max(W / img.width, H / img.height)
    bg = img.resize((round(img.width * sc), round(img.height * sc)), Image.LANCZOS)
    x = (bg.width - W) // 2; y = (bg.height - H) // 2
    bg = bg.crop((x, y, x + W, y + H)).filter(ImageFilter.GaussianBlur(28))
    # foreground: contain
    sc2 = min(W / img.width, H / img.height)
    fg = img.resize((round(img.width * sc2), round(img.height * sc2)), Image.LANCZOS)
    bg.paste(fg, ((W - fg.width) // 2, (H - fg.height) // 2))
    q = 84
    while True:
        buf = io.BytesIO()
        bg.save(buf, "JPEG", quality=q, optimize=True)
        data = buf.getvalue()
        if len(data) <= 300_000 or q <= 60:
            break
        q -= 6
    print(f"   cover {url.split('/')[-1]} -> {len(data)//1024} KB q{q}")
    return base64.b64encode(data).decode()

