def commons_url(file_title):
    params = {"action": "query", "titles": file_title, "prop": "imageinfo",
              "iiprop": "url|size|mime", "format": "json"}
    url = "https://commons.wikimedia.org/w/api.php?" + urllib.parse.urlencode(params)
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    d = json.load(urllib.request.urlopen(req, timeout=30, context=CTX))
    for p in d.get("query", {}).get("pages", {}).values():
        ii = p.get("imageinfo", [{}])
        if ii and ii[0].get("url"):
            return ii[0]["url"], ii[0].get("width", 0), ii[0].get("height", 0)
    return None, 0, 0

def fetch_bytes(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    return urllib.request.urlopen(req, timeout=60, context=CTX).read()

def make_cover_b64(candidates):
    """Compose first usable candidate onto a 1600x900 (16:9) canvas:
    blurred darkened fill + sharp centered subject, so a center-crop never cuts faces."""
    for title in candidates:
        try:
            url, w, h = commons_url(title)
            if not url:
                print(f"   resolve fail: {title}"); continue
            raw = fetch_bytes(url)
            img = Image.open(io.BytesIO(raw)).convert("RGB")
            if min(img.size) < 300:
                print(f"   too small {img.size}: {title}"); continue
            CW, CH = 1600, 900
            # background: cover-crop + blur + darken
            scale = max(CW / img.width, CH / img.height)
            bw, bh = int(img.width * scale) + 1, int(img.height * scale) + 1
            bg = img.resize((bw, bh), Image.LANCZOS)
            left = (bw - CW) // 2; top = (bh - CH) // 2
            bg = bg.crop((left, top, left + CW, top + CH)).filter(ImageFilter.GaussianBlur(28))
            bg = ImageEnhance.Brightness(bg).enhance(0.5)
            # foreground: fit within margins, centered
            fscale = min((CW - 120) / img.width, (CH - 70) / img.height)
            fw, fh = max(1, int(img.width * fscale)), max(1, int(img.height * fscale))
            fg = img.resize((fw, fh), Image.LANCZOS)
            canvas = bg.copy()
            canvas.paste(fg, ((CW - fw) // 2, (CH - fh) // 2))
            # encode under 300 KB
            for q in (85, 80, 74, 68, 60):
                buf = io.BytesIO()
                canvas.save(buf, format="JPEG", quality=q, optimize=True)
                data = buf.getvalue()
                if len(data) <= 300 * 1024:
                    break
            b64 = base64.b64encode(data).decode("ascii")
            print(f"   cover OK {title.split(':',1)[-1][:42]} -> {len(data)//1024}KB jpeg")
            return b64
        except Exception as e:
            print(f"   img error {title}: {type(e).__name__} {str(e)[:80]}")
    return None

