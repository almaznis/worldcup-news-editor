def _get(url, timeout=40):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return r.read()

def commons_best(query, surname):
    """Search Wikimedia Commons for a real landscape photo; return 1600px thumb URL."""
    api = ("https://commons.wikimedia.org/w/api.php?action=query&format=json"
           "&generator=search&gsrnamespace=6&gsrlimit=25"
           "&gsrsearch=" + urllib.parse.quote(query) +
           "&prop=imageinfo&iiprop=url|size|mime&iiurlwidth=1600")
    data = json.loads(_get(api).decode("utf-8"))
    pages = (data.get("query") or {}).get("pages") or {}
    best, best_score = None, -999
    for p in pages.values():
        title = p.get("title", "")
        ii = (p.get("imageinfo") or [{}])[0]
        mime = ii.get("mime", "")
        w, h = ii.get("width", 0), ii.get("height", 0)
        thumb = ii.get("thumburl")
        if mime not in ("image/jpeg", "image/png") or not thumb or w < 700:
            continue
        tl = title.lower()
        if any(bad in tl for bad in ("logo", "emblem", "badge", "coat of arms",
                                     "map", "diagram", "icon", "flag", "stamp",
                                     "signature", "trophy")):
            continue
        score = 0
        if w >= h:            score += 3          # landscape preferred
        if w >= 1200:         score += 1
        if surname.lower() in tl: score += 4
        if "cropped" in tl:   score += 1
        if score > best_score:
            best, best_score = thumb, score
    return best

def optimize_169(raw):
    """Return base64 JPEG, 1600x900, subject centered on blurred fill, <300KB."""
    im = Image.open(io.BytesIO(raw))
    if im.mode in ("RGBA", "P", "LA"):
        im = im.convert("RGB")
    elif im.mode != "RGB":
        im = im.convert("RGB")
    CW, CH = 1600, 900
    # blurred cover background
    bw, bh = im.size
    scale = max(CW / bw, CH / bh)
    bg = im.resize((max(1, int(bw*scale)), max(1, int(bh*scale))), Image.LANCZOS)
    left = (bg.width - CW) // 2; top = (bg.height - CH) // 2
    bg = bg.crop((left, top, left + CW, top + CH)).filter(ImageFilter.GaussianBlur(28))
    bg = Image.eval(bg, lambda x: int(x * 0.82))  # slight darken
    # contained foreground
    scale = min(CW / bw, CH / bh)
    fw, fh = max(1, int(bw*scale)), max(1, int(bh*scale))
    fg = im.resize((fw, fh), Image.LANCZOS)
    bg.paste(fg, ((CW - fw)//2, (CH - fh)//2))
    for q in (85, 80, 75, 70, 65):
        buf = io.BytesIO()
        bg.save(buf, "JPEG", quality=q, optimize=True)
        if buf.tell() <= 300*1024 or q == 65:
            return base64.b64encode(buf.getvalue()).decode("ascii"), buf.tell()
    return None, 0

def cover_b64(query, surname, label):
    try:
        url = commons_best(query, surname)
        if not url:
            print(f"  ✗ no Commons match for {label}")
            return None
        raw = _get(url)
        b64, size = optimize_169(raw)
        print(f"  ✓ {label}: {url.split('/')[-1][:48]} -> {size//1024}KB")
        return b64
    except Exception as e:
        print(f"  ✗ {label} image error: {e}")
        return None

