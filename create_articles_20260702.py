# ─────────────────────────── publish ───────────────────────────────────────
def post(items):
    payload = json.dumps({"articles": items}).encode("utf-8")
    req = urllib.request.Request(ENDPOINT, data=payload, method="POST",
        headers={"Content-Type": "application/json", "x-agent-secret": SECRET})
    with urllib.request.urlopen(req, timeout=120) as r:
        return r.status, json.loads(r.read().decode("utf-8"))

def api_obj(a):
    return {k: a[k] for k in ("title","slug","body","excerpt","category","type",
                              "image_url","image_base64","sources","source_type")}

print("Publishing 8 articles...")
status, resp = post([api_obj(a) for a in ARTICLES])
results = resp.get("results", [])
print("HTTP", status)
by_slug = {r.get("slug","?"): r for r in results}
for a in ARTICLES:
    r = by_slug.get(a["slug"], {})
    print(f"  {a['slug']}: {r.get('status','?')} {r.get('error','')}")

# retry errors
errs = [a for a in ARTICLES if by_slug.get(a["slug"],{}).get("status") != "inserted"]
if errs:
    print("Retrying", len(errs), "failed items...")
    time.sleep(3)
    status2, resp2 = post([api_obj(a) for a in errs])
    for r in resp2.get("results", []):
        by_slug[r.get("slug","?")] = r
        print(f"  retry {r.get('slug')}: {r.get('status')} {r.get('error','')}")

