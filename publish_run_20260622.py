def fetch_optimized_b64(url: str) -> str | None:
    """Download an image, fit it onto a 1600x900 (16:9) canvas with a blurred
    fill (so faces are never center-cropped), re-encode as JPEG q82 (EXIF
    stripped), and return base64. Returns None on failure."""
    try:
        req = urllib.request.Request(url, headers={"User-Agent": UA})
        with urllib.request.urlopen(req, timeout=45) as r:
            raw = r.read()
        src = Image.open(io.BytesIO(raw)).convert("RGB")
        W, H = 1600, 900
        # blurred, zoomed background that covers the whole 16:9 canvas
        scale_bg = max(W / src.width, H / src.height)
        bg = src.resize((int(src.width * scale_bg) + 1, int(src.height * scale_bg) + 1), Image.LANCZOS)
        left = (bg.width - W) // 2
        top = (bg.height - H) // 2
        bg = bg.crop((left, top, left + W, top + H)).filter(ImageFilter.GaussianBlur(28))
        # foreground fully contained, centered
        scale_fg = min(W / src.width, H / src.height)
        fg = src.resize((max(1, int(src.width * scale_fg)), max(1, int(src.height * scale_fg))), Image.LANCZOS)
        bg.paste(fg, ((W - fg.width) // 2, (H - fg.height) // 2))
        out = io.BytesIO()
        bg.save(out, format="JPEG", quality=82, optimize=True)
        data = out.getvalue()
        enc = base64.b64encode(data).decode("ascii")
        print(f"  ✓ {url.split('/')[-1][:48]:48}  {len(raw)//1024} KB → {len(data)//1024} KB jpeg")
        return enc
    except Exception as exc:
        print(f"  ✗ {url}: {exc}")
        return None


