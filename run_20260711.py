def to_169_b64(raw, target_w=1600, max_kb=300):
    """Crop/pad to 16:9 keeping faces (bias crop toward the top), optimize < max_kb."""
    im = Image.open(io.BytesIO(raw)).convert("RGB")
    w, h = im.size
    tar = 16/9
    ar = w/h
    if ar > tar:                       # too wide -> crop sides, centered
        nw = int(round(h*tar)); x = (w-nw)//2
        im = im.crop((x, 0, x+nw, h))
    elif ar < tar:                     # too tall -> crop height, keep top (heads)
        nh = int(round(w/tar)); top = int(round((h-nh)*0.12))
        im = im.crop((0, top, w, top+nh))
    th = int(round(target_w*9/16))
    im = im.resize((target_w, th), Image.LANCZOS)
    q = 85
    while q >= 55:
        buf = io.BytesIO()
        im.save(buf, "JPEG", quality=q, optimize=True)  # PIL drops EXIF by default
        data = buf.getvalue()
        if len(data) <= max_kb*1024:
            break
        q -= 5
    return base64.b64encode(data).decode("ascii"), len(data)//1024, im.size

