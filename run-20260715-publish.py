def commons_thumb_url(title, width=1600):
    req = urllib.request.Request(
        COMMONS_API + "?" + urllib.parse.urlencode({
            "action": "query", "format": "json", "titles": title,
            "prop": "imageinfo", "iiprop": "url|size|mime", "iiurlwidth": width,
        }), headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=40) as r:
        data = json.loads(r.read().decode())
    pages = data["query"]["pages"]
    ii = next(iter(pages.values()))["imageinfo"][0]
    return ii.get("thumburl") or ii.get("url"), ii.get("url")


def optimize_landscape(raw):
    """Return JPEG bytes, 16:9, max 1600px wide, subject centered, < ~420KB."""
    im = Image.open(io.BytesIO(raw))
    im = ImageOps.exif_transpose(im).convert("RGB")
    TW, TH = 1600, 900  # 16:9
    w, h = im.size
    # scale so the image covers the 16:9 frame, then center-crop
    scale = max(TW / w, TH / h)
    nw, nh = max(TW, int(round(w * scale))), max(TH, int(round(h * scale)))
    im = im.resize((nw, nh), Image.LANCZOS)
    left = (nw - TW) // 2
    top = (nh - TH) // 2
    im = im.crop((left, top, left + TW, top + TH))
    for q in (85, 80, 74, 68, 60):
        buf = io.BytesIO()
        im.save(buf, "JPEG", quality=q, optimize=True, progressive=True)
        if buf.tell() <= 430_000:
            return buf.getvalue()
    return buf.getvalue()


